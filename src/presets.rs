pub struct GamePreset {
    pub id: &'static str,
    pub game: &'static str,
    pub tagline: &'static str,
    pub genre: &'static str,
    pub accent: (u8, u8, u8),
    pub exe_names: &'static [&'static str],
    pub install_paths: &'static [&'static str],
    pub match_names: &'static [&'static str],
    pub steam_folders: &'static [&'static str],
    pub tweak_ids: &'static [&'static str],
    pub launch_options: &'static str,
    pub config_path: &'static str,
    pub in_game: &'static [&'static str],
    pub notes: &'static [&'static str],
    pub provider: &'static str,
}

