pub fn all() -> &'static [GamePreset] {
    GAMES
}

pub fn by_id(id: &str) -> Option<&'static GamePreset> {
    GAMES.iter().find(|p| p.id == id)
}

pub fn by_name(name: &str) -> Option<&'static GamePreset> {
    GAMES
        .iter()
        .find(|p| p.game.eq_ignore_ascii_case(name) || p.id.eq_ignore_ascii_case(name))
}

pub fn system_all() -> &'static [SystemPreset] {
    SYSTEM_PRESETS
}

pub fn system_by_id(id: &str) -> Option<&'static SystemPreset> {
    SYSTEM_PRESETS.iter().find(|p| p.id == id)
}
